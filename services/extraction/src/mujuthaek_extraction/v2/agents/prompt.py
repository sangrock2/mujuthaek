"""V2 에이전트 공통 지시: V1 분야 규칙(원칙·섹션별로 넣을 것·값 작성·누락 기록)에 V2 근거 id·도구 규칙을 더합니다.

V1의 「출력은 JSON 하나」 문장과 「3. 근거 인용」 절(quotes·quoteRefs로 인용을 직접 씀)만 V2 규칙으로 바꿉니다.
같은 공고의 담당들은 이 지시와 도구가 같아 앞부분이 프롬프트 캐시를 함께 씁니다(담당마다 다른 할 일은 뒤 메시지로).
"""

from __future__ import annotations

import re

from mujuthaek_extraction.rules.base import FieldRules

V1_OUTPUT_LINE = re.compile(r"^출력은 지정된 JSON 스키마.*$", re.M)
V1_QUOTES_PART = re.compile(r"^# 3\. 근거 인용\n.*?(?=^# 4\.)", re.M | re.S)

AGENT_OUTPUT = (
    "당신은 섹션 담당 에이전트입니다. 원문을 도구로 읽고, 항목을 도구로 넣고, 근거는 원문 조각의 id로 남깁니다.\n"
    "끝나면 도구 없이 짧게 답합니다. 이 지시에서 「인용한다」·`quoteRefs`는 항목의 `evidence`로 그 원문 조각의 id를 가리키는 것을 말합니다(3장)."
)

EVIDENCE_RULES = """# 3. 근거(evidence)
1. 원문은 id가 붙은 조각입니다: 줄 `p3.12`(3쪽 12번째 줄), 표 행 `t4-1.r3`, 표 칸 `t4-1.r3.c2`(0부터), 엑셀·그림 판독 묶음 `x1.4`·`g1.t1.r2`.
   쪽 표시·표 표시·`[열 제목]`·`↳` 줄은 프로그램이 붙인 것이라 id가 없고 근거가 아닙니다.
2. 모든 항목에 `evidence`를 1개 이상 붙입니다. 근거 하나는 id(`"t4-1.r3.c2"`) 또는 `{"id": "p3.12", "part": "<그 줄 안의 일부 글자 그대로>"}`입니다.
   - 값 하나는 그 값이 든 칸 id나, 줄이 길면 그 줄의 값이 든 구간(part)으로 가리킵니다. 표는 한 행 또는 한 칸씩 가리킵니다.
   - 인용 글은 프로그램이 id로 원문에서 꺼내므로 글자를 옮겨 쓰지 않습니다(`quotes`·`quoteRefs`는 쓰지 않음).
3. 같은 문장이 여러 곳에 있으면 대상·순위·주택형이 드러나는 쪽을 가리킵니다. 다른 쪽에 있는 두 근거가 필요하면 근거를 두 개 붙입니다.

## 3-1. 표 읽기
- `view_table`은 표의 열 제목(`columns`, 병합 칸을 풀어 위에서 아래로 이은 것)과 행·칸 id를 보여 줍니다. 값이 무엇인지(모집 수인지 건설 호수인지,
  어느 계층·요금안인지)는 열 제목으로 판단하고 칸 개수를 세어 맞추지 않습니다.
- 합쳐진 칸은 빈 칸으로 보이니 위 행의 값(단지명·주택형 등)을 이어받아 해석하되, 근거는 그 행에 실제로 글자가 있는 칸으로 합니다.
- 다음 쪽 맨 위에 머리 행 없이 같은 모양의 표가 이어지면 앞 표의 이어짐입니다. 앞 표의 열 제목으로 읽습니다.

"""

TOOL_RULES = """
# 6. 도구로 일하는 법
1. 맡은 섹션과 관련된 곳만 읽습니다. 처음 메시지의 원문 차례에서 위치를 정하고 `view_lines`·`view_table`·`search`로 읽습니다.
   한 차례에 도구를 여럿 부를 수 있습니다(쪽 여러 곳을 한 번에). 원문 전체를 처음부터 끝까지 읽지 않습니다.
2. `add_items`로 항목을 넣습니다. 한 번에 15개 안팎씩 나눠 넣습니다(한 번 답의 길이에 상한이 있어 너무 많으면 잘림).
   칸은 값이 있는 것만 적습니다(null·빈 목록은 프로그램이 채움). 형식이 틀리거나 근거 id가 없으면 그 항목만 「위치: 이유」 오류로 돌아오니 고쳐서 다시 넣습니다.
3. 넣은 항목은 `update_item`(바꿀 칸만)·`remove_item`으로 고칩니다. 판정·화면에 필요한 값을 원문에서 찾지 못했으면 `report_missing`으로 적습니다.
   한 차례의 도구들은 동시에 실행되므로, 방금 넣은 항목을 고치거나 그 항목의 누락을 적는 일은 다음 차례에 합니다.
4. 끝내기 전에 `check`로 맡은 섹션의 검증 문제를 봅니다. 원문으로 고칠 수 있는 것은 고치고, 섹션마다 `set_coverage`로 상태를 정합니다.
5. 차례와 비용에 상한이 있습니다. 같은 곳을 다시 읽지 않고, 다 넣었으면 바로 끝냅니다. 끝낼 때는 도구 없이 한두 문장으로
   넣은 것·남은 문제를 답합니다.
"""


def system_prompt(rules: FieldRules) -> str:
    base = rules.system_prompt()
    base = V1_OUTPUT_LINE.sub(AGENT_OUTPUT, base, count=1)
    if not V1_QUOTES_PART.search(base):
        raise ValueError("V1 지시에서 「3. 근거 인용」 절을 찾지 못했습니다(지시 버전이 바뀌었으면 V2 지시를 맞춥니다)")
    base = V1_QUOTES_PART.sub(EVIDENCE_RULES, base, count=1)
    return base.rstrip() + "\n" + TOOL_RULES
