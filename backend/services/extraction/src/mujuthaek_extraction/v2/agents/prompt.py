"""V2 에이전트 공통 지시: V1 분야 규칙(원칙·섹션별로 넣을 것·값 작성·누락 기록)에 V2 근거 id·도구 규칙을 더합니다.

V1의 「출력은 JSON 하나」 문장과 「3. 근거 인용」 절(quotes·quoteRefs로 인용을 직접 씀)만 V2 규칙으로 바꿉니다.
같은 공고의 담당들은 이 지시·도구·첫 메시지(원문 전체)가 같아 앞부분이 프롬프트 캐시를 함께 씁니다(담당마다 다른 할 일은 둘째 메시지).
위치·공급 묶음 절은 뺍니다: 그 섹션은 V1 구조 호출이 자기 지시로 넣고 담당(일정·자격·선정·서류)은 넣지 않습니다. 앞부분은 담당의 모든
차례가 다시 읽으므로(2026-11-08 저장 결과: 평균 5.9만 토큰 중 지시·도구가 3.2만) 쓰지 않는 지시를 두지 않습니다.
"""

from __future__ import annotations

import re

from mujuthaek_extraction.rules.base import FieldRules

V1_OUTPUT_LINE = re.compile(r"^출력은 지정된 JSON 스키마.*$", re.M)
V1_QUOTES_PART = re.compile(r"^# 3\. 근거 인용\n.*?(?=^# 4\.)", re.M | re.S)
# 「## 2-2. 위치(`locations`)」·「## 2-3. 공급(`supplyGroups`)」 절(아래 「### 묶음」 같은 작은 절까지, 다음 #·## 머리 전까지)
V1_STRUCTURE_PARTS = re.compile(r"^## 2-\d+\. [^\n]*\(`(?:locations|supplyGroups)`\)\n.*?(?=^#{1,2} )", re.M | re.S)

AGENT_OUTPUT = (
    "당신은 섹션 담당 에이전트입니다. 첫 메시지의 원문(조각마다 id)을 보고, 맡은 섹션 항목을 도구로 넣고, 근거는 원문 조각의 id로 남깁니다.\n"
    "끝낼 때는 finish 도구를 부릅니다. 이 지시에서 「인용한다」·`quoteRefs`는 항목의 `evidence`로 그 원문 조각의 id를 가리키는 것을 말합니다(3장)."
)

EVIDENCE_RULES = """# 3. 근거(evidence)
1. 원문은 첫 메시지에 id가 붙은 조각으로 있습니다: 줄 `p3.12 …`(3쪽 12번째 줄), 표 행 `t4-1.r3 c0=… | c2=…`(행 id 뒤에 칸 번호=칸 글자),
   엑셀·그림 판독 묶음 `x1.4`·`g1.t1.r2`. `[p3]`·`[표 …]` 머리와 `열:`은 프로그램이 붙인 것이라 근거가 아닙니다.
2. 모든 항목에 `evidence`를 1개 이상 붙입니다. 근거 하나는 id(`"t4-1.r3.c2"`) 또는 `{"id": "p3.12", "part": "<그 줄 안의 일부 글자 그대로>"}`입니다.
   - 값 하나는 그 값이 든 칸 id(행 id + `.c<칸 번호>`)나, 줄이 길면 그 줄의 값이 든 구간(part)으로 가리킵니다. 표는 한 행 또는 한 칸씩 가리킵니다.
   - 빈 칸(합쳐진 칸)은 행에 적혀 있지 않아 근거가 될 수 없습니다. 글자가 있는 칸이나 행을 가리킵니다.
   - 인용 글은 프로그램이 id로 원문에서 꺼내므로 글자를 옮겨 쓰지 않습니다(`quotes`·`quoteRefs`는 쓰지 않음).
   - `originalText`(원문 문장)는 비워 두면 첫 근거의 원문으로 채워집니다. 적는다면 원문 글자 그대로 적습니다.
3. 같은 문장이 여러 곳에 있으면 대상·순위·주택형이 드러나는 쪽을 가리킵니다. 다른 쪽에 있는 두 근거가 필요하면 근거를 두 개 붙입니다.

## 3-1. 표 읽기
- 표 머리의 `열:`은 열 제목(병합 칸을 풀어 위에서 아래로 이은 것)을 칸 번호와 함께 보여 줍니다. 값이 무엇인지(모집 수인지 건설 호수인지,
  어느 계층·요금안인지)는 칸 번호의 열 제목으로 판단하고, 행에 보이는 칸 순서로 짐작하지 않습니다.
- 합쳐진 칸은 행에서 빠져 있으니 위 행의 값(단지명·주택형·평가 항목 등)을 이어받아 해석하되, 근거는 그 행에 실제로 글자가 있는 칸으로 합니다.
- 다음 쪽 맨 위에 머리 행 없이 같은 모양의 표가 이어지면 앞 표의 이어짐입니다. 앞 표의 열 제목으로 읽습니다.

"""

TOOL_RULES = """
# 6. 도구로 일하는 법
1. 원문 전체는 첫 메시지에, 맡은 일은 둘째 메시지에 있습니다. 원문 전체에서 맡은 섹션의 내용을 빠짐없이 찾습니다.
2. 첫 차례에 맡은 섹션의 항목을 모두 넣습니다. 섹션마다 `add_<섹션>`(예: `add_eligibility`)을 쓰고, 그 도구의 입력 형식이 곧 그 섹션 항목 형식입니다.
   호출 하나에 50개 안팎까지 넣고, 더 많으면 같은 차례에 같은 도구를 여러 번 부릅니다(차례를 나눠 조금씩 넣지 않음).
   칸은 값이 있는 것만 적습니다(null·빈 목록은 프로그램이 채움). 적용 범위 `scope`는 특정 위치·공급 묶음·대상에 한정되지 않으면 적지 않고
   (프로그램이 공고 전체로 채움), 대상만 다르면 `level: "NOTICE"`에 `targetGroups`만 적습니다. `LOCATION`·`SUPPLY_GROUP`은 그 id를 함께 적을 때만
   쓰고, `supplyCategory: "ALL"`·`resolution: "RESOLVED"`·빈 목록은 적지 않습니다.
   도구 목록에는 다른 담당의 섹션 도구도 있지만(담당들이 같은 목록을 씀) 맡은 섹션 것만 씁니다.
3. 형식이 틀리거나 근거가 없는 항목은 넣을 때 그 항목만 「위치: 이유」로 거절됩니다. 거절된 항목은 `update_item`(같은 id, 틀린 칸만)으로
   고치면 넣어집니다(항목 전체를 다시 보내지 않음). 도구를 쓴 다음에는 프로그램이 초안을 결합·검증기로 보고
   맡은 섹션의 문제를 「검증 결과」 메시지로 알려 줍니다. 「고칠 것」(형식·계약·근거 오류)은 `update_item`(바꿀 칸만)·`remove_item`·
   `add_<섹션>`으로 반드시 고칩니다. 「확인할 것」(의심 경고)은 원문과 대조해 실제로 틀렸거나 빠졌을 때만 고치고, 원문상 맞으면 그대로 둡니다
   (그 항목만 사람이 확인). 경고를 없애려고 원문에 없는 값·예외를 넣거나 맞는 값을 바꾸지 않습니다. 판정·화면에 필요한데 원문에 없는 값은
   `report_missing`으로 적습니다.
   한 차례의 도구들은 동시에 실행되므로 방금 넣은 항목을 고치거나 그 항목의 누락을 적는 일은 다음 차례에 합니다.
4. 항목을 넣은 섹션은 다 넣은 것(EXTRACTED)으로 보므로 `set_coverage`를 부르지 않습니다. `set_coverage`는 원문에 있는데 넣지 못한
   항목이 있을 때(PARTIAL, 섹션 전체가 사람 확인으로 감)와 원문에 그 섹션 내용이 없을 때(NOT_IN_SOURCE)만 씁니다.
   고치지 않고 남긴 검증 문제는 PARTIAL의 이유가 아닙니다.
5. 끝낼 때는 `finish`(넣은 것·남은 문제 한두 문장)를 부릅니다. 마지막 넣기·고치기와 같은 차례에 함께 부르면 차례가 줄어듭니다:
   그 차례의 도구가 실행된 뒤 검증에 새 문제가 없으면 그대로 끝나고, 새 문제가 있으면 검증 결과로 알려 줍니다.
   고칠 것이 없고 확인할 것은 한 번 고쳐 보고도 같은 것(「다시」 표시)만 남았으면 `finish`만 부릅니다. 차례와 비용에 상한이 있습니다.
"""


def system_prompt(rules: FieldRules) -> str:
    base = rules.system_prompt()
    base = V1_OUTPUT_LINE.sub(AGENT_OUTPUT, base, count=1)
    if not V1_QUOTES_PART.search(base):
        raise ValueError("V1 지시에서 「3. 근거 인용」 절을 찾지 못했습니다(지시 버전이 바뀌었으면 V2 지시를 맞춥니다)")
    base = V1_QUOTES_PART.sub(EVIDENCE_RULES, base, count=1)
    base = V1_STRUCTURE_PARTS.sub("", base)
    return base.rstrip() + "\n" + TOOL_RULES
